$PrivateApiPath = Join-Path $SourcePath 'private\api'
$DtoPath = Join-Path $SourcePath 'classes\dto'
$GeneratedTestPath = Join-Path (Split-Path -Parent $SourcePath) 'tests\Unit\Private\ImmichApi.Generated.Tests.ps1'
$GeneratedDtoTestPath = Join-Path (Split-Path -Parent $SourcePath) 'tests\Unit\Private\ImmichDto.Generated.Tests.ps1'

$Files = @{}
$RouteTests = New-Object System.Collections.Generic.List[object]
$OperationNames = @{}
foreach ($PathProperty in $Spec.paths.PSObject.Properties)
{
    $PathItem = $PathProperty.Value
    if (Test-Property $PathItem 'parameters')
    {
        throw "Path-level parameters on '$($PathProperty.Name)' are not supported."
    }
    foreach ($Method in $HttpMethods)
    {
        if (-not (Test-Property $PathItem $Method))
        {
            continue
        }
        $Route = New-RouteFunction $PathItem.PSObject.Properties[$Method].Value $Method $PathProperty.Name $RootSecured
        if ($OperationNames.ContainsKey($Route.Name))
        {
            throw "Operations $($OperationNames[$Route.Name]) and $Method $($PathProperty.Name) both generate '$($Route.Name)'."
        }
        $OperationNames[$Route.Name] = "$Method $($PathProperty.Name)"
        $Files[(Join-Path $PrivateApiPath ($Route.Name + '.ps1'))] = $Route.Text
        $RouteTests.Add($Route.Tests)
    }
}

$Files[$GeneratedTestPath] = New-GeneratedTestFileText $RouteTests.ToArray()

if (@(Get-ClassEmissionOrder).Count -gt 0)
{
    $Files[(Join-Path $DtoPath $DtoFileName)] = New-DtoFileText

    $DtoTests = New-Object System.Collections.Generic.List[object]
    $DoneClasses = @{}
    foreach ($ClassName in (Get-ClassEmissionOrder))
    {
        $DtoTests.Add((New-DtoTests $ClassName (Get-SchemaEntry $ClassName) $DoneClasses))
        $DoneClasses[$ClassName] = $true
    }
    $Files[$GeneratedDtoTestPath] = New-GeneratedTestFileText $DtoTests.ToArray()

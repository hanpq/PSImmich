#Requires -Version 5.1
<#
.SYNOPSIS
    Generates the internal 1:1 Immich API route functions and DTO classes from an OpenAPI specification.
.DESCRIPTION
    Writes one private function per operation to source/private/api (Invoke-ImmichApi<OperationId>) and
    every object schema to source/classes/dto/ImmichDto.class.ps1. The DTO classes live in a single file
    because ModuleBuilder orders class files by path, which would break dependency order across files.

    Generated files carry a marker line. Only files with the marker are updated or removed, so
    hand-written files are never touched. Only files whose content changed are written.
.PARAMETER SpecPath
    OpenAPI JSON specification. Defaults to api/api.3.3.6.json.
.PARAMETER SourcePath
    Module source folder containing the private and classes folders. Defaults to source.
.PARAMETER Check
    Writes nothing. Throws when generated files are missing, stale or unexpected.
.EXAMPLE
    .\tools\New-ImmichApiLayer.ps1
.EXAMPLE
    .\tools\New-ImmichApiLayer.ps1 -Check
#>
[CmdletBinding()]
param(
    [string]$SpecPath = (Join-Path $PSScriptRoot '..\api\api.3.4.0.json'),
    [string]$SourcePath = (Join-Path $PSScriptRoot '..\source'),
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

$MarkerText = 'AUTO-GENERATED by tools/New-ImmichApiLayer.ps1. Do not edit by hand.'
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
# Platform line endings match the QA line-ending rule; comparisons ignore them so checkouts with autocrlf or LF agree.
$NewLine = [System.Environment]::NewLine
$HttpMethods = @('get', 'post', 'put', 'patch', 'delete')
$DtoFileName = 'ImmichDto.class.ps1'

# Names the generated functions already use or that PowerShell reserves. Colliding wire names get a 'Value' suffix.
$ReservedParameterNames = @(
    'Session', 'ImmichSession', 'Body', 'RawBody', 'Headers', 'QueryParameters', 'ContentType', 'Request',
    'RelativePath', 'OutFilePath', 'NoAuth', 'FormData', 'FileInfo', 'Verbose', 'Debug', 'ErrorAction',
    'WarningAction', 'InformationAction', 'ErrorVariable', 'WarningVariable', 'InformationVariable',
    'OutVariable', 'OutBuffer', 'PipelineVariable', 'WhatIf', 'Confirm', 'ProgressAction'
)

function Test-Property($Object, [string]$Name)
{
    return ($null -ne $Object) -and ($null -ne $Object.PSObject.Properties[$Name])
}

function ConvertTo-PascalCase([string]$Name)
{
    $Parts = @([regex]::Split($Name, '[^A-Za-z0-9]+') | Where-Object { $_ })
    if ($Parts.Count -eq 0)
    {
        throw "Cannot derive a PowerShell name from '$Name'."
    }
    return (($Parts | ForEach-Object { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) }) -join '')
}

function ConvertTo-SingleQuoted([string]$Value)
{
    return "'" + $Value.Replace("'", "''") + "'"
}

function Get-RefName([string]$Ref)
{
    $Prefix = '#/components/schemas/'
    if (-not $Ref.StartsWith($Prefix))
    {
        throw "Unsupported reference '$Ref'. Only $Prefix references are supported."
    }
    return $Ref.Substring($Prefix.Length)
}

function Get-SchemaEntry([string]$Name)
{
    $Entry = $Script:Schemas.PSObject.Properties[$Name]
    if ($null -eq $Entry)
    {
        throw "Reference to missing schema '$Name'."
    }
    return $Entry.Value
}

function Assert-SupportedSchema($Schema, [string]$Context)
{
    # A single-member allOf is OpenAPI 3.0's wrapper for a nullable $ref and is resolved by the callers.
    if ((Test-Property $Schema 'allOf') -and @($Schema.allOf).Count -eq 1)
    {
        return
    }
    foreach ($Keyword in 'allOf', 'oneOf', 'anyOf', 'not')
    {
        if (Test-Property $Schema $Keyword)
        {
            throw "$Context uses '$Keyword', which the generator does not support."
        }
    }
}

# Maps a scalar schema to a PowerShell type name. Enums keep their values for ValidateSet.
function Get-ScalarType($Schema, [string]$Context)
{
    Assert-SupportedSchema $Schema $Context
    if (Test-Property $Schema 'enum')
    {
        return [pscustomobject]@{ Type = 'string'; Values = @($Schema.enum) }
    }
    $Format = ''
    if (Test-Property $Schema 'format')
    {
        $Format = [string]$Schema.format
    }
    switch ([string]$Schema.type)
    {
        'string'
        {
            if ($Format -eq 'date-time') { $Type = 'datetime' }
            elseif ($Format -eq 'binary') { $Type = 'object' }
            else { $Type = 'string' }
        }
        'integer'
        {
            if ($Format -eq 'int64') { $Type = 'long' } else { $Type = 'int' }
        }
        'number' { $Type = 'double' }
        'boolean' { $Type = 'bool' }
        'object' { $Type = 'object' }
        default { throw "$Context has unsupported schema type '$($Schema.type)'." }
    }
    return [pscustomobject]@{ Type = $Type; Values = $null }
}

# Route parameters: scalars or arrays of strings (repeated query keys).
function Get-RouteParameterType($Schema, [string]$Context)
{
    if (Test-Property $Schema '$ref')
    {
        $Target = Get-SchemaEntry (Get-RefName ([string]$Schema.'$ref'))
        return Get-RouteParameterType $Target $Context
    }
    if ([string]$Schema.type -eq 'array')
    {
        $Item = Get-RouteParameterType $Schema.items $Context
        if ($Item.Array -or $Item.Type -ne 'string')
        {
            throw "$Context has an unsupported array parameter type."
        }
        return [pscustomobject]@{ Type = 'string'; Array = $true; Values = $Item.Values }
    }
    $Scalar = Get-ScalarType $Schema $Context
    return [pscustomobject]@{ Type = $Scalar.Type; Array = $false; Values = $Scalar.Values }
}

function New-ParameterRecord([string]$Name, [string]$Wire, $ParameterType, [bool]$Mandatory, [string]$ParameterSet = '')
{
    $TypeName = $ParameterType.Type
    if ($ParameterType.Array)
    {
        $TypeName += '[]'
    }
    $Attributes = ''
    $AttributeArguments = @()
    if ($Mandatory)
    {
        $AttributeArguments += 'Mandatory'
    }
    if ($ParameterSet)
    {
        $AttributeArguments += "ParameterSetName='$ParameterSet'"
    }
    if ($AttributeArguments.Count -gt 0)
    {
        $Attributes += '[Parameter(' + ($AttributeArguments -join ', ') + ')]'
    }
    if ($ParameterType.Values)
    {
        $Attributes += '[ValidateSet(' + ((@($ParameterType.Values) | ForEach-Object { ConvertTo-SingleQuoted ([string]$_) }) -join ', ') + ')]'
    }
    return [pscustomobject]@{
        Name        = $Name
        Wire        = $Wire
        TypeName    = $TypeName
        Mandatory   = $Mandatory
        Declaration = $Attributes + '[' + $TypeName + ']$' + $Name
    }
}

function Get-PSParameterName([string]$WireName, [hashtable]$UsedNames, [string]$Context)
{
    $Name = ConvertTo-PascalCase $WireName
    if ($ReservedParameterNames -contains $Name)
    {
        $Name += 'Value'
    }
    if ($UsedNames.ContainsKey($Name))
    {
        throw "$Context maps more than one parameter to '$Name'."
    }
    $UsedNames[$Name] = $true
    return $Name
}

function Get-PathExpression([string]$Path, [hashtable]$PathParams, [string]$Context)
{
    $Parts = New-Object System.Collections.Generic.List[string]
    $Last = 0
    foreach ($Match in [regex]::Matches($Path, '\{([^}]+)\}'))
    {
        $Literal = $Path.Substring($Last, $Match.Index - $Last)
        if ($Literal)
        {
            $Parts.Add((ConvertTo-SingleQuoted $Literal))
        }
        $Wire = $Match.Groups[1].Value
        if (-not $PathParams.ContainsKey($Wire))
        {
            throw "$Context has path placeholder '{$Wire}' without a declared path parameter."
        }
        $Parts.Add('[uri]::EscapeDataString($' + $PathParams[$Wire] + ')')
        $Last = $Match.Index + $Match.Length
    }
    $Tail = $Path.Substring($Last)
    if ($Tail)
    {
        $Parts.Add((ConvertTo-SingleQuoted $Tail))
    }
    return (@($Parts) -join ' + ')
}

# Sample values drive the generated route tests; they are fixed so the output is deterministic.
function Get-TestSampleValue($ParameterType, [string]$Context)
{
    if ($ParameterType.Array)
    {
        if ($ParameterType.Values)
        {
            return ,@(@($ParameterType.Values | ForEach-Object { [string]$_ }) | Select-Object -First 2)
        }
        return ,@('sample-a', 'sample-b')
    }
    if ($ParameterType.Values)
    {
        return [string](@($ParameterType.Values)[0])
    }
    switch ($ParameterType.Type)
    {
        'string' { return 'sample' }
        'int' { return [int]1 }
        'long' { return [long]1 }
        'double' { return [double]1.5 }
        'bool' { return $true }
        'datetime' { return [datetime]::SpecifyKind([datetime]'2024-01-02T03:04:05', [DateTimeKind]::Utc) }
        default { throw "$Context has no test sample for type '$($ParameterType.Type)'." }
    }
}

function ConvertTo-TestText($Value)
{
    $Invariant = [System.Globalization.CultureInfo]::InvariantCulture
    if ($Value -is [bool])
    {
        if ($Value) { return 'True' }
        return 'False'
    }
    if ($Value -is [datetime]) { return $Value.ToString('o', $Invariant) }
    if ($Value -is [double]) { return $Value.ToString($Invariant) }
    return [string]$Value
}

function ConvertTo-TestLiteral($Value)
{
    if ($Value -is [array])
    {
        return '@(' + ((@($Value) | ForEach-Object { ConvertTo-TestLiteral $_ }) -join ', ') + ')'
    }
    if ($Value -is [string]) { return ConvertTo-SingleQuoted $Value }
    if ($Value -is [bool])
    {
        if ($Value) { return '$true' }
        return '$false'
    }
    if ($Value -is [datetime]) { return "([datetime]'" + (ConvertTo-TestText $Value) + "')" }
    return ConvertTo-TestText $Value
}

# Emits Pester blocks that call the generated function and assert the mocked transport call.
function New-RouteTests([string]$FunctionName, [string]$HttpMethodName, [string]$Path, [object[]]$Bindings, [string]$BodyKind, [bool]$Secured)
{
    $Multipart = $BodyKind -eq 'multipart'
    $MockTarget = 'InvokeImmichRestMethod'
    $MockBody = '{ }'
    if ($Multipart)
    {
        $MockTarget = 'Invoke-MultipartHttpUpload'
        $MockBody = "{ '{}' }"
    }

    $Bindings = @($Bindings)
    $ExpectedPath = $Path
    foreach ($Binding in @($Bindings | Where-Object { $_.Kind -eq 'path' }))
    {
        $ExpectedPath = $ExpectedPath.Replace('{' + $Binding.Wire + '}', [uri]::EscapeDataString((ConvertTo-TestText $Binding.Value)))
    }

    $Conditions = @()
    if (-not $Multipart)
    {
        $Conditions += '$Method -eq ' + (ConvertTo-SingleQuoted $HttpMethodName)
    }
    $Conditions += '$RelativePath -eq ' + (ConvertTo-SingleQuoted $ExpectedPath)
    if (-not $Multipart)
    {
        if ($Secured) { $Conditions += '-not [bool]$NoAuth' } else { $Conditions += '[bool]$NoAuth' }
    }

    $CallArgs = @($Bindings | Where-Object { $_.Kind -eq 'path' } | ForEach-Object { ' -' + $_.Name + ' ' + (ConvertTo-TestLiteral $_.Value) })
    switch ($BodyKind)
    {
        'json'
        {
            $CallArgs += ' -Body @{}'
            $Conditions += '$Body -is [hashtable]'
        }
        'form'
        {
            $CallArgs += ' -RawBody ' + (ConvertTo-SingleQuoted 'sample=1')
            $Conditions += '$RawBody -eq ' + (ConvertTo-SingleQuoted 'sample=1')
            $Conditions += '$ContentType -eq ' + (ConvertTo-SingleQuoted 'application/x-www-form-urlencoded')
        }
        'multipart'
        {
            $CallArgs += ' -FileInfo [System.IO.FileInfo]' + (ConvertTo-SingleQuoted 'sample.bin')
        }
    }

    $BasicArgs = @($CallArgs)
    $BasicConditions = @($Conditions)
    $AllArgs = @($CallArgs)
    $AllConditions = @($Conditions)
    $HasOptional = $false
    foreach ($Binding in @($Bindings | Where-Object { $_.Kind -ne 'path' }))
    {
        $Arg = ' -' + $Binding.Name + ' ' + (ConvertTo-TestLiteral $Binding.Value)
        $Wire = ConvertTo-SingleQuoted $Binding.Wire
        if ($Binding.Kind -eq 'query')
        {
            if ($Binding.Value -is [array])
            {
                $Condition = '(@($QueryParameters[' + $Wire + ']) -join ' + (ConvertTo-SingleQuoted ',') + ') -eq ' + (ConvertTo-SingleQuoted (@($Binding.Value) -join ','))
            }
            else
            {
                $Condition = '$QueryParameters[' + $Wire + '] -eq ' + (ConvertTo-TestLiteral $Binding.Value)
            }
        }
        else
        {
            $Condition = '$Headers[' + $Wire + '] -eq ' + (ConvertTo-SingleQuoted (ConvertTo-TestText $Binding.Value))
        }
        if ($Binding.Mandatory)
        {
            $BasicArgs += $Arg
            $BasicConditions += $Condition
        }
        else
        {
            $HasOptional = $true
        }
        $AllArgs += $Arg
        $AllConditions += $Condition
    }

    $Cases = @(@{ Title = 'Should send the route method and path with required parameters'; Args = $BasicArgs; Conditions = $BasicConditions })
    if ($HasOptional)
    {
        $Cases += @{ Title = 'Should forward every supplied query and header parameter'; Args = $AllArgs; Conditions = $AllConditions }
    }

    $Lines = New-Object System.Collections.Generic.List[string]
    $Lines.Add("    Describe '$FunctionName' -Tag 'Unit', 'ImmichApiLayer', 'Generated' {")
    $Lines.Add('        BeforeAll {')
    $Lines.Add("            Mock -CommandName $MockTarget -MockWith $MockBody")
    $Lines.Add('        }')
    for ($Index = 0; $Index -lt $Cases.Count; $Index++)
    {
        $Case = $Cases[$Index]
        if ($Index -gt 0)
        {
            $Lines.Add('')
        }
        $Lines.Add("        It '$($Case.Title)' {")
        $Lines.Add("            $FunctionName$(@($Case.Args) -join '')")
        $Lines.Add("            Should -Invoke -CommandName $MockTarget -Times 1 -Exactly -ParameterFilter {")
        $Lines.Add('                ' + ((@($Case.Conditions) | ForEach-Object { '(' + $_ + ')' }) -join ' -and '))
        $Lines.Add('            }')
        $Lines.Add('        }')
    }
    $Lines.Add('    }')
    return ($Lines -join $NewLine)
}

function New-GeneratedTestFileText([object[]]$RouteTests)
{
    $Header = @'
BeforeDiscovery {
    $RootItem = Get-Item $PSScriptRoot
    while ($RootItem.GetDirectories().Name -notcontains 'source')
    {
        $RootItem = $RootItem.Parent
    }
    $ProjectPath = $RootItem.FullName
    $ProjectName = (Get-ChildItem $ProjectPath\*\*.psd1 | Where-Object {
            ($_.Directory.Name -eq 'source') -and
            $(try
                {
                    Test-ModuleManifest $_.FullName -ErrorAction Stop
                }
                catch
                {
                    $false
                })
        }
    ).BaseName

    Import-Module $ProjectName -Force
}

InModuleScope $ProjectName {
'@
    $Head = (@("# $MarkerText") + @($Header -split "\r?\n")) -join $NewLine
    return $Head + $NewLine + (@($RouteTests) -join ($NewLine + $NewLine)) + $NewLine + '}' + $NewLine
}

function New-RouteFunction($Operation, [string]$Method, [string]$Path, [bool]$RootSecured)
{
    $OperationId = [string]$Operation.operationId
    if ([string]::IsNullOrWhiteSpace($OperationId))
    {
        throw "Operation $Method $Path has no operationId."
    }
    $Context = "$($Method.ToUpperInvariant()) $Path ($OperationId)"
    $FunctionName = 'Invoke-ImmichApi' + (ConvertTo-PascalCase $OperationId)
    $HttpMethodName = ConvertTo-PascalCase $Method

    $UsedNames = @{}
    $PathParams = @{}
    $Declarations = New-Object System.Collections.Generic.List[object]
    $QueryParams = New-Object System.Collections.Generic.List[object]
    $HeaderParams = New-Object System.Collections.Generic.List[object]
    $Bindings = New-Object System.Collections.Generic.List[object]

    $OperationParameters = @()
    if (Test-Property $Operation 'parameters')
    {
        $OperationParameters = @($Operation.parameters)
    }
    foreach ($Parameter in $OperationParameters)
    {
        if (Test-Property $Parameter '$ref')
        {
            throw "$Context uses a parameter reference, which is not supported."
        }
        $Wire = [string]$Parameter.name
        $Location = [string]$Parameter.in
        $Mandatory = [bool]$Parameter.required
        $ParameterType = Get-RouteParameterType $Parameter.schema $Context
        switch ($Location)
        {
            'path'
            {
                if ($ParameterType.Array)
                {
                    throw "$Context uses an array path parameter, which is not supported."
                }
                $Name = Get-PSParameterName $Wire $UsedNames $Context
                $PathParams[$Wire] = $Name
                $Declarations.Add((New-ParameterRecord $Name $Wire $ParameterType $true))
                $Bindings.Add([pscustomobject]@{ Kind = 'path'; Name = $Name; Wire = $Wire; Mandatory = $true; Value = (Get-TestSampleValue $ParameterType $Context) })
            }
            'query'
            {
                if (-not ($ParameterType.Type -in @('string', 'datetime', 'int', 'double', 'bool')))
                {
                    throw "$Context query parameter '$Wire' has unsupported type '$($ParameterType.Type)'."
                }
                $Name = Get-PSParameterName $Wire $UsedNames $Context
                $Record = New-ParameterRecord $Name $Wire $ParameterType $Mandatory
                $QueryParams.Add($Record)
                $Declarations.Add($Record)
                $Bindings.Add([pscustomobject]@{ Kind = 'query'; Name = $Name; Wire = $Wire; Mandatory = $Mandatory; Value = (Get-TestSampleValue $ParameterType $Context) })
            }
            'header'
            {
                if ($ParameterType.Array -or $ParameterType.Type -eq 'object')
                {
                    throw "$Context header parameter '$Wire' must be a scalar."
                }
                $Name = Get-PSParameterName $Wire $UsedNames $Context
                $Record = New-ParameterRecord $Name $Wire $ParameterType $Mandatory
                $HeaderParams.Add($Record)
                $Declarations.Add($Record)
                $Bindings.Add([pscustomobject]@{ Kind = 'header'; Name = $Name; Wire = $Wire; Mandatory = $Mandatory; Value = (Get-TestSampleValue $ParameterType $Context) })
            }
            default
            {
                throw "$Context has unsupported parameter location '$Location'."
            }
        }
    }

    $Lines = New-Object System.Collections.Generic.List[string]
    $ContentTypes = @()
    $BodyKind = 'none'
    $FileFieldName = $null
    $FormFields = $null
    $AdditionalFileFields = @()
    if (Test-Property $Operation 'requestBody')
    {
        $RequestBody = $Operation.requestBody
        $ContentTypes = @($RequestBody.content.PSObject.Properties.Name)
        if ($ContentTypes.Count -ne 1)
        {
            throw "$Context must declare exactly one request content type."
        }
        $BodyMandatory = [bool]$RequestBody.required
        switch ($ContentTypes[0])
        {
            'application/json'
            {
                $BodyKind = 'json'
                # Body (hashtable) and RawBody (pre-serialized JSON text) are mutually exclusive
                # parameter sets. RawBody avoids ConvertTo-Json depth limits for nested documents.
                $Declarations.Add((New-ParameterRecord 'Body' 'Body' ([pscustomobject]@{ Type = 'hashtable'; Array = $false; Values = $null }) $BodyMandatory 'Json'))
                $Declarations.Add((New-ParameterRecord 'RawBody' 'RawBody' ([pscustomobject]@{ Type = 'string'; Array = $false; Values = $null }) $BodyMandatory 'RawJson'))
            }
            'application/x-www-form-urlencoded'
            {
                $BodyKind = 'form'
                $Declarations.Add((New-ParameterRecord 'RawBody' 'RawBody' ([pscustomobject]@{ Type = 'string'; Array = $false; Values = $null }) $BodyMandatory))
            }
            'multipart/form-data'
            {
                $BodyKind = 'multipart'
                $Schema = $RequestBody.content.'multipart/form-data'.schema
                if (-not (Test-Property $Schema '$ref'))
                {
                    throw "$Context multipart body must reference a schema."
                }
                $FormSchema = Get-SchemaEntry (Get-RefName ([string]$Schema.'$ref'))
                $BinaryFields = @($FormSchema.properties.PSObject.Properties | Where-Object { [string]$_.Value.format -eq 'binary' })
                if ($BinaryFields.Count -eq 0)
                {
                    throw "$Context multipart body must have a binary field."
                }
                $FileFieldName = $BinaryFields[0].Name
                $FormFields = @($FormSchema.properties.PSObject.Properties | Where-Object { $_.Name -ne $FileFieldName } | ForEach-Object { $_.Name })
                if ($Method -ne 'post')
                {
                    throw "$Context multipart upload must use POST."
                }
                if ($PathParams.Count -gt 0)
                {
                    throw "$Context multipart upload with path parameters is not supported."
                }
                $Declarations.Add((New-ParameterRecord 'FileInfo' 'FileInfo' ([pscustomobject]@{ Type = 'System.IO.FileInfo'; Array = $false; Values = $null }) $true))
                for ($BinaryIndex = 1; $BinaryIndex -lt $BinaryFields.Count; $BinaryIndex++)
                {
                    $AdditionalFileFields += $BinaryFields[$BinaryIndex].Name
                    $AdditionalName = ConvertTo-PascalCase $BinaryFields[$BinaryIndex].Name
                    $Declarations.Add((New-ParameterRecord $AdditionalName $AdditionalName ([pscustomobject]@{ Type = 'System.IO.FileInfo'; Array = $false; Values = $null }) $false))
                }
                $Declarations.Add((New-ParameterRecord 'FormData' 'FormData' ([pscustomobject]@{ Type = 'hashtable'; Array = $false; Values = $null }) $false))
            }
            default
            {
                throw "$Context has unsupported request content type '$($ContentTypes[0])'."
            }
        }
    }

    $ResponseIsOctet = $false
    foreach ($Response in $Operation.responses.PSObject.Properties)
    {
        if ($Response.Name -match '^2' -and (Test-Property $Response.Value 'content'))
        {
            if (@($Response.Value.content.PSObject.Properties.Name) -contains 'application/octet-stream')
            {
                $ResponseIsOctet = $true
            }
        }
    }
    if ($ResponseIsOctet)
    {
        $Declarations.Add((New-ParameterRecord 'OutFilePath' 'OutFilePath' ([pscustomobject]@{ Type = 'System.IO.FileInfo'; Array = $false; Values = $null }) $false))
    }

    $Declarations.Add([pscustomobject]@{ Name = 'ImmichSession'; Declaration = '[ImmichSession]$ImmichSession = $null' })

    $Secured = $RootSecured
    if (Test-Property $Operation 'security')
    {
        $Secured = @($Operation.security).Count -gt 0
    }

    $Lines.Add('    $RelativePath = ' + (Get-PathExpression $Path $PathParams $Context))
    if ($QueryParams.Count -gt 0)
    {
        $Lines.Add('    $QueryParameters = @{}')
        foreach ($Query in $QueryParams)
        {
            $Lines.Add('    if ($PSBoundParameters.ContainsKey(''' + $Query.Name + ''')) { $QueryParameters[''' + $Query.Wire + '''] = $' + $Query.Name + ' }')
        }
    }
    if ($HeaderParams.Count -gt 0)
    {
        $Lines.Add('    $Headers = @{}')
        foreach ($Header in $HeaderParams)
        {
            $Lines.Add('    if ($PSBoundParameters.ContainsKey(''' + $Header.Name + ''')) { $Headers[''' + $Header.Wire + '''] = [string]$' + $Header.Name + ' }')
        }
    }

    if ($BodyKind -eq 'multipart')
    {
        if ($HeaderParams.Count -eq 0)
        {
            $Lines.Add('    $Headers = @{}')
        }
        if ($QueryParams.Count -eq 0)
        {
            $Lines.Add('    $QueryParameters = @{}')
        }
        $Lines.Add('    $AdditionalFiles = @{}')
        foreach ($AdditionalField in $AdditionalFileFields)
        {
            $AdditionalName = ConvertTo-PascalCase $AdditionalField
            $Lines.Add('    if ($PSBoundParameters.ContainsKey(''' + $AdditionalName + ''')) { $AdditionalFiles[''' + $AdditionalField + '''] = $' + $AdditionalName + ' }')
        }
        $Lines.Add('    $Response = Invoke-MultipartHttpUpload -RelativePath $RelativePath -Session $ImmichSession -FormData $FormData -FileInfo $FileInfo -FileFieldName ''' + $FileFieldName + ''' -AdditionalFiles $AdditionalFiles -QueryParameters $QueryParameters -Headers $Headers')
        $Lines.Add('    if (-not [string]::IsNullOrEmpty($Response))')
        $Lines.Add('    {')
        $Lines.Add('        ConvertFrom-Json -InputObject $Response')
        $Lines.Add('    }')
    }
    else
    {
        $Lines.Add('    $Request = @{')
        $Lines.Add('        Method        = ''' + $HttpMethodName + '''')
        $Lines.Add('        RelativePath  = $RelativePath')
        $Lines.Add('        ImmichSession = $ImmichSession')
        $Lines.Add('    }')
        if (-not $Secured)
        {
            $Lines.Add('    $Request.NoAuth = $true')
        }
        if ($QueryParams.Count -gt 0)
        {
            $Lines.Add('    if ($QueryParameters.Count -gt 0) { $Request.QueryParameters = $QueryParameters }')
        }
        if ($HeaderParams.Count -gt 0)
        {
            $Lines.Add('    if ($Headers.Count -gt 0) { $Request.Headers = $Headers }')
        }
        switch ($BodyKind)
        {
            'json'
            {
                $Lines.Add('    if ($PSBoundParameters.ContainsKey(''Body'')) { $Request.Body = $Body }')
                $Lines.Add('    if ($PSBoundParameters.ContainsKey(''RawBody'')) { $Request.RawBody = $RawBody }')
            }
            'form'
            {
                $Lines.Add('    $Request.ContentType = ''application/x-www-form-urlencoded''')
                $Lines.Add('    if ($PSBoundParameters.ContainsKey(''RawBody'')) { $Request.RawBody = $RawBody }')
            }
        }
        if ($ResponseIsOctet)
        {
            $Lines.Add('    if ($PSBoundParameters.ContainsKey(''OutFilePath'')) { $Request.OutFilePath = $OutFilePath }')
        }
        $Lines.Add('    InvokeImmichRestMethod @Request')
    }

    $DeclarationLines = @($Declarations | ForEach-Object { '        ' + $_.Declaration })
    $Text = New-Object System.Collections.Generic.List[string]
    $Text.Add("# $MarkerText")
    $Text.Add("function $FunctionName")
    $Text.Add('{')
    $CmdletBindingLine = '    [CmdletBinding()]'
    if ($BodyKind -eq 'json')
    {
        $CmdletBindingLine = "    [CmdletBinding(DefaultParameterSetName = 'Json')]"
    }
    $Text.Add($CmdletBindingLine)
    # Names mirror the Immich operationIds on purpose, so the plural nouns are kept.
    $Text.Add("    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseSingularNouns', '', Justification = 'Name mirrors the Immich operationId.')]")
    $Text.Add('    param(')
    for ($Index = 0; $Index -lt $DeclarationLines.Count; $Index++)
    {
        $Separator = ','
        if ($Index -eq $DeclarationLines.Count - 1)
        {
            $Separator = ''
        }
        $Text.Add($DeclarationLines[$Index] + $Separator)
    }
    $Text.Add('    )')
    $Text.Add('')
    foreach ($Line in $Lines)
    {
        $Text.Add($Line)
    }
    $Text.Add('}')

    $Tests = New-RouteTests $FunctionName $Method $Path $Bindings.ToArray() $BodyKind $Secured
    return [pscustomobject]@{ Name = $FunctionName; Text = (@($Text) -join $NewLine) + $NewLine; Tests = $Tests }
}

function Get-ClassDependencies($Schema)
{
    $Dependencies = New-Object System.Collections.Generic.List[string]
    foreach ($Property in $Schema.properties.PSObject.Properties)
    {
        $Target = $Property.Value
        if ([string]$Target.type -eq 'array')
        {
            $Target = $Target.items
        }
        if (Test-Property $Target '$ref')
        {
            $Name = Get-RefName ([string]$Target.'$ref')
            if (Test-ClassSchema (Get-SchemaEntry $Name))
            {
                $Dependencies.Add($Name)
            }
        }
    }
    return $Dependencies
}

function Test-ClassSchema($Schema)
{
    return (Test-Property $Schema 'properties') -and -not (Test-Property $Schema 'enum')
}

# Depth-first order so dependencies are declared before the classes that reference them.
function Get-ClassEmissionOrder
{
    $Names = @($Script:Schemas.PSObject.Properties | Where-Object { Test-ClassSchema $_.Value } | ForEach-Object { $_.Name } | Sort-Object)
    $Order = New-Object System.Collections.Generic.List[string]
    $Visited = @{}
    function Visit-Class([string]$Name)
    {
        if ($Visited.ContainsKey($Name))
        {
            return
        }
        $Visited[$Name] = $true
        foreach ($Dependency in (Get-ClassDependencies (Get-SchemaEntry $Name)))
        {
            Visit-Class $Dependency
        }
        $Order.Add($Name)
    }
    foreach ($Name in $Names)
    {
        Visit-Class $Name
    }
    return $Order
}

# Property type. Class references are typed only once the target class is already emitted (Done);
# cyclic references fall back to [object] to keep the file loadable.
function Get-DtoPropertyType($Property, [string]$Context, [hashtable]$Done)
{
    if (Test-Property $Property '$ref')
    {
        $Name = Get-RefName ([string]$Property.'$ref')
        $Target = Get-SchemaEntry $Name
        if (Test-Property $Target 'enum')
        {
            return [pscustomobject]@{ Type = 'string'; Array = $false; Kind = 'scalar' }
        }
        if (Test-ClassSchema $Target)
        {
            if ($Done.ContainsKey($Name))
            {
                return [pscustomobject]@{ Type = $Name; Array = $false; Kind = 'class' }
            }
            return [pscustomobject]@{ Type = 'object'; Array = $false; Kind = 'raw' }
        }
        return Get-DtoPropertyType $Target $Context $Done
    }
    if ((Test-Property $Property 'allOf') -and @($Property.allOf).Count -eq 1)
    {
        return Get-DtoPropertyType @($Property.allOf)[0] $Context $Done
    }
    if ((Test-Property $Property 'anyOf') -or (Test-Property $Property 'oneOf'))
    {
        $Members = @()
        if (Test-Property $Property 'anyOf') { $Members += @($Property.anyOf) }
        if (Test-Property $Property 'oneOf') { $Members += @($Property.oneOf) }
        if ($Members.Count -eq 0 -or @($Members | Where-Object { -not (Test-Property $_ '$ref') }).Count -gt 0)
        {
            throw "$Context uses a union that is not a set of references, which the generator does not support."
        }
        return [pscustomobject]@{ Type = 'object'; Array = $false; Kind = 'raw' }
    }
    if (-not (Test-Property $Property 'type') -and -not (Test-Property $Property 'enum'))
    {
        $Constraints = @($Property.PSObject.Properties.Name | Where-Object {
                $_ -notin @('title', 'description', 'nullable', 'default', 'example', 'deprecated', 'readOnly', 'writeOnly') -and
                $_ -notlike 'x-*'
            })
        if ($Constraints.Count -gt 0)
        {
            throw "$Context has an untyped schema with unsupported keywords: $($Constraints -join ', ')."
        }
        return [pscustomobject]@{ Type = 'object'; Array = $false; Kind = 'raw' }
    }
    if ([string]$Property.type -eq 'array')
    {
        $Item = Get-DtoPropertyType $Property.items $Context $Done
        $Kind = $Item.Kind
        if ($Kind -eq 'class')
        {
            $Kind = 'classarray'
        }
        return [pscustomobject]@{ Type = $Item.Type; Array = $true; Kind = $Kind }
    }
    $Scalar = Get-ScalarType $Property $Context
    if ($Scalar.Type -eq 'int' -and (($Property.maximum -gt [int]::MaxValue) -or ($Property.minimum -lt [int]::MinValue)))
    {
        $Scalar = [pscustomobject]@{ Type = 'long' }
    }
    $Kind = 'scalar'
    if ($Scalar.Type -eq 'object')
    {
        $Kind = 'raw'
    }
    return [pscustomobject]@{ Type = $Scalar.Type; Array = $false; Kind = $Kind }
}

function New-ClassText([string]$Name, $Schema, [hashtable]$Done)
{
    $Context = "DTO $Name"
    $Text = New-Object System.Collections.Generic.List[string]
    $Constructor = New-Object System.Collections.Generic.List[string]
    $Seen = @{}
    $HasStringId = $false
    $Text.Add("class $Name")
    $Text.Add('{')
    foreach ($Property in $Schema.properties.PSObject.Properties)
    {
        $PropertyName = $Property.Name
        if ($PropertyName -notmatch '^[A-Za-z_][A-Za-z0-9_]*$')
        {
            throw "$Context has property '$PropertyName' that is not a valid PowerShell identifier."
        }
        if ($Seen.ContainsKey($PropertyName))
        {
            throw "$Context has duplicate property '$PropertyName'."
        }
        $Seen[$PropertyName] = $true

        $Type = Get-DtoPropertyType $Property.Value $Context $Done
        $TypeName = $Type.Type
        if ($Type.Array)
        {
            $TypeName += '[]'
        }
        if ($PropertyName -ceq 'id' -and $Type.Kind -eq 'scalar' -and $Type.Type -eq 'string' -and -not $Type.Array)
        {
            $HasStringId = $true
        }
        $Text.Add("    [$TypeName]`$$PropertyName")

        $Source = "`$Source.$PropertyName"
        switch ($Type.Kind)
        {
            'class' { $Constructor.Add("        if (`$null -ne $Source) { `$this.$PropertyName = [$($Type.Type)]::new($Source) }") }
            'classarray' { $Constructor.Add("        if (`$null -ne $Source) { `$this.$PropertyName = @($Source | ForEach-Object { [$($Type.Type)]::new(`$_) }) }") }
            default { $Constructor.Add("        if (`$null -ne $Source) { `$this.$PropertyName = $Source }") }
        }
    }
    $Text.Add('')
    $Text.Add("    $Name()")
    $Text.Add('    {')
    $Text.Add('    }')
    $Text.Add('')
    $Text.Add("    $Name([object]`$Source)")
    $Text.Add('    {')
    foreach ($Line in $Constructor)
    {
        $Text.Add($Line)
    }
    $Text.Add('    }')
    if ($HasStringId)
    {
        $Text.Add('')
        $Text.Add('    [string] ToString()')
        $Text.Add('    {')
        $Text.Add('        return $this.id')
        $Text.Add('    }')
    }
    $Text.Add('}')
    return (@($Text) -join $NewLine)
}

function New-DtoFileText
{
    $Classes = New-Object System.Collections.Generic.List[string]
    $Done = @{}
    foreach ($Name in (Get-ClassEmissionOrder))
    {
        $Classes.Add((New-ClassText $Name (Get-SchemaEntry $Name) $Done))
        $Done[$Name] = $true
    }
    return "# $MarkerText$NewLine" + (@($Classes) -join "$NewLine$NewLine") + $NewLine
}

# Typed sample for one DTO property; arrays hold two copies of the scalar sample.
function New-DtoPropertySample($Property, [string]$Context)
{
    $Name = $Property.Name
    if ($Property.Kind -eq 'class')
    {
        return [pscustomobject]@{ Value = '[pscustomobject]@{}'; Check = "`$Dto.$Name.GetType().Name | Should -Be '$($Property.Type)'" }
    }
    if ($Property.Kind -eq 'classarray')
    {
        return [pscustomobject]@{ Value = '@([pscustomobject]@{})'; Check = "@(`$Dto.$Name).Count | Should -Be 1" }
    }
    $ScalarType = $Property.Type
    if ($ScalarType -eq 'object')
    {
        $ScalarType = 'string'
    }
    $Item = ConvertTo-TestLiteral (Get-TestSampleValue ([pscustomobject]@{ Type = $ScalarType; Array = $false }) $Context)
    if ($Property.Array)
    {
        return [pscustomobject]@{ Value = "@($Item, $Item)"; Check = "@(`$Dto.$Name).Count | Should -Be 2" }
    }
    return [pscustomobject]@{ Value = $Item; Check = "`$Dto.$Name | Should -Be $Item" }
}

# Emits Pester blocks that cover a DTO's default and source-object constructors.
function New-DtoTests([string]$Name, $Schema, [hashtable]$Done)
{
    $Context = "DTO $Name"
    $Properties = New-Object System.Collections.Generic.List[object]
    foreach ($Property in $Schema.properties.PSObject.Properties)
    {
        $Type = Get-DtoPropertyType $Property.Value $Context $Done
        $Properties.Add([pscustomobject]@{ Name = $Property.Name; Type = $Type.Type; Array = $Type.Array; Kind = $Type.Kind })
    }

    $Lines = New-Object System.Collections.Generic.List[string]
    $Lines.Add("    Describe '$Name' -Tag 'Unit', 'ImmichDtoLayer', 'Generated' {")
    $Lines.Add("        It 'Should create an instance with the default constructor' {")
    $Lines.Add("            [$Name]::new() | Should -BeOfType ([$Name])")
    $Lines.Add('        }')
    if ($Properties.Count -gt 0)
    {
        $Values = New-Object System.Collections.Generic.List[string]
        $Checks = New-Object System.Collections.Generic.List[string]
        foreach ($Property in $Properties)
        {
            $Sample = New-DtoPropertySample $Property $Context
            $Values.Add("                $($Property.Name) = $($Sample.Value)")
            $Checks.Add("            $($Sample.Check)")
        }
        $Lines.Add("        It 'Should map every property from a source object' {")
        $Lines.Add('            $Source = [pscustomobject]@{')
        $Lines.AddRange($Values)
        $Lines.Add('            }')
        $Lines.Add("            `$Dto = [$Name]::new(`$Source)")
        $Lines.AddRange($Checks)
        $Lines.Add('        }')
    }
    if (@($Properties | Where-Object { $_.Name -ceq 'id' -and $_.Kind -eq 'scalar' -and $_.Type -eq 'string' -and -not $_.Array }).Count -gt 0)
    {
        $Lines.Add("        It 'Should return the id from ToString' {")
        $Lines.Add("            [$Name]::new([pscustomobject]@{ id = 'sample' }).ToString() | Should -Be 'sample'")
        $Lines.Add('        }')
    }
    $Lines.Add('    }')
    return (@($Lines) -join $NewLine)
}

function Write-GeneratedFile([string]$Path, [string]$Content)
{
    $Existing = $null
    if (Test-Path -LiteralPath $Path)
    {
        $Existing = [System.IO.File]::ReadAllText($Path)
    }
    if (($Existing -replace "`r`n", "`n") -ceq ($Content -replace "`r`n", "`n"))
    {
        return 'Unchanged'
    }
    if ($Check)
    {
        return 'Stale'
    }
    [System.IO.File]::WriteAllText($Path, $Content, $Utf8NoBom)
    return 'Written'
}

